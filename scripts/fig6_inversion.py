"""Fig. 6 — synthetic-data inversion over the full twenty-dimensional chart.

Synthetic terminal-voltage data are generated by the grouped DFN/P2D model of
``dfn_grouped.py`` at a known parameter theta*, once without noise and once
with additive Gaussian noise (standard deviation 0.1 mV).  A Levenberg--
Marquardt least-squares fit over all twenty log-coordinates is then started
from many random points.  Each start perturbs every Q18 coordinate
log-uniformly within a factor 1.5 of its true value and then applies a random
gauge element: lambda_c log-uniform in [0.1, 10] (common scaling of gamma and
nu_e^q) and r_f / R_ser uniform in [0.05, 0.95] at the start's R_ser.

Usage:  python fig6_inversion.py            (compute + plot)
        python fig6_inversion.py --plot     (plot from saved results)
"""
from __future__ import annotations

import sys
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from dfn_grouped import GroupedDFN, NAMES, Q18, Q18_NAMES, true_theta  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "reports" / "fig6_inversion_results.npz"
REP = ROOT / "reports" / "fig6_inversion_report.txt"

N_STARTS = 40
NOISE_V = 1.0e-4
PROTOCOL = [(20, 600, 2.5), (700, 20, -4.0), (760, 15, 5.0), (900, 200, -3.0),
            (1200, 40, 6.0), (1400, 500, 2.0), (2000, 10, -6.0), (2100, 300, -2.0)]
MODEL_KW = dict(tol=1e-10, pulses=PROTOCOL, t_end=2700.0, dt=5.0, N=(4, 3, 4), Nr=4)
I_GC = [NAMES.index(n) for n in ("gamma", "nu_n", "nu_s", "nu_p")]
I_RF, I_KS = NAMES.index("r_f"), NAMES.index("kappa_s")

_M = None


def model():
    global _M
    if _M is None:
        _M = GroupedDFN(**MODEL_KW)
    return _M


def draw_start(rng, theta):
    """Random start: Q18 within a factor 1.5, then a random gauge element."""
    th = theta.copy()
    q_idx = list(range(14))
    th[q_idx] *= np.exp(rng.uniform(-np.log(1.5), np.log(1.5), 14))
    zeta_t = theta[I_GC[0]] / theta[I_GC[1:]]
    zeta0 = zeta_t * np.exp(rng.uniform(-np.log(1.5), np.log(1.5), 3))
    R_t = theta[I_RF] + 1.0 / theta[I_KS]
    R0 = R_t * np.exp(rng.uniform(-np.log(1.5), np.log(1.5)))
    lam = np.exp(rng.uniform(np.log(0.1), np.log(10.0)))
    gam0 = theta[I_GC[0]] * lam
    th[I_GC[0]] = gam0
    th[I_GC[1:]] = gam0 / zeta0
    f = rng.uniform(0.05, 0.95)
    th[I_RF] = f * R0
    th[I_KS] = 1.0 / ((1.0 - f) * R0)
    return th


def lm_fit(p0, Vd, max_iter=80):
    M = model()

    def sim(p):
        try:
            return np.array(M.sim(p)).ravel()
        except RuntimeError:
            return None

    p = p0.copy()
    mu = None
    c_prev = np.inf
    for it in range(max_iter):
        V, J = M.voltage_jac(p)
        r = V - Vd
        c = float(r @ r)
        U, s, Vt = np.linalg.svd(J, full_matrices=False)
        g = U.T @ r
        if mu is None:
            mu = s[0] ** 2 * 1e-2
        accepted = False
        while mu < s[0] ** 2 * 1e8:
            d = -(Vt.T @ (s / (s ** 2 + mu) * g))
            nd = np.linalg.norm(d)
            if nd > 1.0:
                d /= nd
            Vn = sim(p + d)
            if Vn is not None and float((Vn - Vd) @ (Vn - Vd)) < c:
                p = p + d
                mu = max(mu / 5.0, s[0] ** 2 * 1e-16)
                accepted = True
                break
            mu *= 4.0
        if not accepted:
            break
        if c_prev - c < 1e-12 * c and it > 5:
            break
        c_prev = c
    V = np.array(M.sim(p)).ravel()
    return p, float(np.sqrt(np.mean((V - Vd) ** 2))), it + 1


def _job(args):
    case, k, p0, Vd = args
    t0 = time.time()
    p, rms, nit = lm_fit(p0, Vd)
    print(f"{case} start {k:02d}: rms={rms:.3e} V, {nit} it, {time.time()-t0:.0f}s", flush=True)
    return case, k, p, rms, nit


def compute():
    theta = true_theta()
    M = model()
    V_true, J = M.voltage_jac(np.log(theta))
    sv = np.linalg.svd(J, compute_uv=False)
    rng = np.random.default_rng(20261110)
    V_noisy = V_true + NOISE_V * rng.standard_normal(V_true.shape)
    V_noisy[0] = V_true[0]
    starts = np.array([draw_start(rng, theta) for _ in range(N_STARTS)])
    jobs = [("clean", k, np.log(starts[k]), V_true) for k in range(N_STARTS)]
    jobs += [("noisy", k, np.log(starts[k]), V_noisy) for k in range(N_STARTS)]
    with Pool(7) as pool:
        out = pool.map(_job, jobs, chunksize=1)
    est = {"clean": np.zeros((N_STARTS, 20)), "noisy": np.zeros((N_STARTS, 20))}
    rms = {"clean": np.zeros(N_STARTS), "noisy": np.zeros(N_STARTS)}
    nit = {"clean": np.zeros(N_STARTS, int), "noisy": np.zeros(N_STARTS, int)}
    for case, k, p, r, n in out:
        est[case][k] = np.exp(p)
        rms[case][k] = r
        nit[case][k] = n
    t = M.tgrid
    u = np.array([float(__import__("casadi").DM(
        __import__("dfn_grouped").current(tt, PROTOCOL))) for tt in t])
    np.savez(RES, theta=theta, starts=starts, est_clean=est["clean"],
             est_noisy=est["noisy"], rms_clean=rms["clean"], rms_noisy=rms["noisy"],
             nit_clean=nit["clean"], nit_noisy=nit["noisy"], sv=sv, t=t, u=u,
             V_true=V_true, V_noisy=V_noisy)


def report(d):
    theta = d["theta"]
    qt = Q18(theta)
    lines = ["# Synthetic-data inversion (grouped DFN/P2D, 20 coordinates)", ""]
    sv = d["sv"]
    lines.append("singular values of dV/dlog(theta) at theta*: " +
                 " ".join(f"{x:.3e}" for x in sv))
    lines.append(f"ratio s18/s1 = {sv[17]/sv[0]:.3e}; s19/s1 = {sv[18]/sv[0]:.3e}; "
                 f"s20/s1 = {sv[19]/sv[0]:.3e}")
    lines.append(f"noise sd = {NOISE_V:.1e} V; samples = {len(d['V_true'])}")
    lines.append("")
    for case in ("clean", "noisy"):
        E = d["est_" + case]
        S = d["starts"]
        Q = np.array([Q18(e) for e in E])
        relq = np.abs(Q / qt - 1.0)
        rels = np.abs(np.array([Q18(s) for s in S]) / qt - 1.0)
        # spread across starts (max/min ratio)
        spread_q = Q.max(0) / Q.min(0) - 1.0
        gam = E[:, I_GC[0]] / theta[I_GC[0]]
        rf = E[:, I_RF] / theta[I_RF]
        ks = E[:, I_KS] / theta[I_KS]
        gam0 = S[:, I_GC[0]] / theta[I_GC[0]]
        rf0 = S[:, I_RF] / theta[I_RF]
        lines += [
            f"## {case}",
            f"rms residual (V): min={d['rms_'+case].min():.3e} max={d['rms_'+case].max():.3e}",
            f"iterations: min={d['nit_'+case].min()} max={d['nit_'+case].max()}",
            f"start max rel err over Q18: median={np.median(rels.max(1)):.3e}",
            f"final max rel err over Q18 (vs truth): max over starts={relq.max():.3e}",
            f"Q18 spread across starts (max/min-1): max over coords={spread_q.max():.3e}",
            "per-coordinate max rel err vs truth: " +
            ", ".join(f"{n}={v:.2e}" for n, v in zip(Q18_NAMES, relq.max(0))),
            "per-coordinate spread across starts: " +
            ", ".join(f"{n}={v:.2e}" for n, v in zip(Q18_NAMES, spread_q)),
            f"gamma/gamma*: range [{gam.min():.3g}, {gam.max():.3g}] (ratio {gam.max()/gam.min():.3g})",
            f"r_f/r_f*: range [{rf.min():.3g}, {rf.max():.3g}] (ratio {rf.max()/rf.min():.3g})",
            f"kappa_s/kappa_s*: range [{ks.min():.3g}, {ks.max():.3g}]",
            f"max |log(gamma_hat/gamma_0)| = {np.abs(np.log(gam/gam0)).max():.3e}",
            f"corr(log r_f_hat, log r_f_0) = {np.corrcoef(np.log(rf), np.log(rf0))[0,1]:.4f}",
            f"max |R_ser_hat/R_ser* - 1| = {np.abs(Q[:,17]/qt[17]-1).max():.3e}",
            "",
        ]
    REP.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    if "--plot" not in sys.argv:
        compute()
    d = dict(np.load(RES))
    report(d)
    from fig6_plot import plot
    plot(d)
